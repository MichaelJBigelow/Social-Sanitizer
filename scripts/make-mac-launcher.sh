#!/bin/bash
# Builds "Social Sanitizer.app", a double-clickable macOS launcher for this checkout.
#
#   scripts/make-mac-launcher.sh [DEST_DIR]     (default: ~/Applications)
#
# The app is a tiny bundle whose executable is a shell script. Because it's an .app
# (not a .command or .py file), macOS runs it without opening Terminal or Python
# Launcher. The script hands its process over to the project's venv Python, writes all
# output to ~/Library/Logs/Social Sanitizer/app.log, and shows an alert if the venv is
# missing. Re-run this script if you move the repository.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST_DIR="${1:-$HOME/Applications}"
APP="$DEST_DIR/Social Sanitizer.app"
BUNDLE_ID="io.github.michaeljbigelow.social-sanitizer"
PY="$REPO/.venv/bin/python"

if [[ ! -x "$PY" ]]; then
  echo "No virtualenv at $REPO/.venv. Set it up first (see README), then re-run." >&2
  exit 1
fi

# Only ever replace a bundle we built ourselves.
if [[ -e "$APP" ]]; then
  existing_id="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$APP/Contents/Info.plist" 2>/dev/null || true)"
  if [[ "$existing_id" != "$BUNDLE_ID" ]]; then
    echo "$APP exists and isn't a Social Sanitizer launcher; not touching it." >&2
    exit 1
  fi
  rm -rf "$APP"
fi

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Social Sanitizer</string>
  <key>CFBundleDisplayName</key><string>Social Sanitizer</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleExecutable</key><string>social-sanitizer</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

# Paths are quoted with printf %q so a repo path with spaces still works.
{
  echo '#!/bin/bash'
  echo '# Generated by scripts/make-mac-launcher.sh; re-run that script instead of editing.'
  printf 'REPO=%q\n' "$REPO"
  cat <<'LAUNCHER'
PY="$REPO/.venv/bin/python"
LOG_DIR="$HOME/Library/Logs/Social Sanitizer"
mkdir -p "$LOG_DIR"

if [[ ! -x "$PY" ]]; then
  /usr/bin/osascript -e 'display alert "Social Sanitizer can’t start" message "The Python environment is missing. Set it up as described in the README, then run scripts/make-mac-launcher.sh again." as critical' >/dev/null
  exit 1
fi

cd "$REPO"
HERE="$(cd "$(dirname "$0")" && pwd)"
# exec: the app's process *becomes* the Python GUI, so nothing is left behind.
if [[ -x "$HERE/Python" ]]; then
  # Run the interpreter from inside this bundle so the Dock shows "Social Sanitizer"
  # and our icon instead of "Python". __PYVENV_LAUNCHER__ is how framework Python's
  # own bin/python stub tells the interpreter which venv to use.
  export __PYVENV_LAUNCHER__="$PY"
  exec "$HERE/Python" -m social_sanitizer </dev/null >>"$LOG_DIR/app.log" 2>&1
fi
exec "$PY" -m social_sanitizer </dev/null >>"$LOG_DIR/app.log" 2>&1
LAUNCHER
} > "$APP/Contents/MacOS/social-sanitizer"
chmod +x "$APP/Contents/MacOS/social-sanitizer"

# Framework Python (python.org, Homebrew) re-launches itself through its own Python.app,
# which makes the Dock say "Python". Copying that small interpreter stub into our bundle
# avoids it. Other Python builds (pyenv, etc.) just use the venv's python directly.
real_py="$("$PY" -c 'import os, sys; print(os.path.realpath(sys.executable))')"
framework_stub="$(dirname "$real_py")/../Resources/Python.app/Contents/MacOS/Python"
if [[ -x "$framework_stub" ]]; then
  cp "$framework_stub" "$APP/Contents/MacOS/Python"
  # Its python.org signature is bound to Python.app's Info.plist, so macOS kills the
  # copy on launch. Re-sign it locally (ad hoc) for this bundle.
  codesign --force --sign - "$APP/Contents/MacOS/Python" 2>/dev/null
fi

# Icon: draw a PNG with Qt, then turn it into an .icns.
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
"$PY" "$REPO/scripts/make_icon.py" "$work/icon.png"
mkdir "$work/AppIcon.iconset"
for size in 16 32 128 256 512; do
  sips -z $size $size "$work/icon.png" --out "$work/AppIcon.iconset/icon_${size}x${size}.png" >/dev/null
  double=$((size * 2))
  sips -z $double $double "$work/icon.png" --out "$work/AppIcon.iconset/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$work/AppIcon.iconset" -o "$APP/Contents/Resources/AppIcon.icns"

# Let Finder/Dock pick up the new bundle and icon right away.
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" >/dev/null 2>&1 || true

echo "Built $APP"
